operador1 = float(input("Introduce el primer número: "))
operador2 = float(input("Introduce el segundo número: "))

print("la suma de operador 1 y operador 2 es:", operador1 + operador2)
print("la resta de operador 1 y operador 2 es:", operador1 - operador2)
print("la multiplicación de operador 1 y operador 2 es:", operador1 * operador2)
print("la división de operador 1 y operador 2 es:", f"{operador1 / operador2:.2f}")
print("la división entera de operador 1 y operador 2 es:", operador1 // operador2)
print("el módulo de operador 1 y operador 2 es:", operador1 % operador2)
print("la potencia de operador 1 y operador 2 es:", operador1 ** operador2)
