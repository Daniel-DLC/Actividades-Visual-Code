# Programa que introduzca por teclado tres tipos de variables y se muestren por pantalla en el siguiente orden: número entero, texto y número decimal.

entero = int(input("Introduce un número entero: "))
texto = input("Introduce un texto: ")
decimal = float(input("Introduce un número decimal: "))

print("El numero entero es: ", entero)
print("El texto es: ", texto)
print("El número decimal es: ", decimal)